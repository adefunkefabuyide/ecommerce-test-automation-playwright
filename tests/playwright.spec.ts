import{ test,expect} from "@playwright/test"
test("automation test",async ({page})=>{
    await page.goto('http://automationexercise.com');
    await expect(page.locator('//img[@src="/static/images/home/logo.png"]')).toBeVisible()
    await page.locator('//a[@href="/login"]').click()
    await expect(page.locator('//h2[text()="New User Signup!"]')).toBeVisible()
    await page.locator('//input[@data-qa="signup-name"]').fill("Jacque")
    await page.locator('//input[@data-qa="signup-email"]').fill("Jacque@example.com")
    await page.locator('//button[@data-qa="signup-button"]').click()
    await expect(page.locator('//b[text()="Enter Account Information"]')).toBeVisible()
    await page.locator("#id_gender2").click()
    await page.locator("#password").fill("1234")
    await page.locator("#days").selectOption({index:4})
    await page.locator("#months").selectOption({"value":"3"})
    await page.locator("#years").selectOption({label:"1992"})
    await page.locator("#newsletter").click()
    await page.locator("#optin").click()
    await page.locator("#first_name").fill("Lesley")
    await page.locator("#last_name").fill("Johnson")
    await page.locator("#company").fill("Clicks")
    await page.locator("#address1").fill("1 College Street")
    await page.locator("#address2").fill("room 2")
    await page.locator("#country").selectOption({"value":"United States"})
    await page.locator("#state").fill("Georgia")
    await page.locator("#city").fill("Altanta")
    await page.locator("#zipcode").fill("30303")
    await page.locator("#mobile_number").fill("123456789")
    await page.locator('//button[@data-qa="create-account"]').click()
    await expect (page.locator('//b[text()="Account Created!"]')).toBeVisible()
    await page.locator('//a[@data-qa="continue-button"]').click()
    await expect (page.locator('//a[contains(normalize-space(), "Logged in as Jacque")]')).toBeVisible()
    await page.locator('//a[@href="/delete_account"]').click()
    await expect (page.locator('//b[text()="Account Deleted!"]')).toBeVisible()
    await page.locator('//a[@data-qa="continue-button"]').click()
})